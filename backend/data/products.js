// Helper: find product by ID
const getProductById = (id) => products.find(p => p.id === id);

// Helper: search products by keyword
const searchProducts = (query) => {
  const q = query.toLowerCase();
  return products.filter(p =>
    p.brand.toLowerCase().includes(q) ||
    p.model.toLowerCase().includes(q) ||
    p.keywords.some(k => k.includes(q)) ||
    p.highlights.some(h => h.toLowerCase().includes(q))
  );
};

// Format product for AI prompt
const formatProductForPrompt = (p) => {
  const specsStr = p.specs ? Object.values(p.specs).join(', ') : '';
  return `${p.brand} ${p.model} (${p.category}) — ₹${p.price.toLocaleString('en-IN')} | ${specsStr} | ${p.highlights.join(', ')}`;
};

// Format all products for AI system prompt
const allProductsSummary = () =>
  products.map(p => formatProductForPrompt(p)).join('\n');

module.exports = { products, getProductById, searchProducts, formatProductForPrompt, allProductsSummary };
